import { test } from 'node:test';
import assert from 'node:assert/strict';
import { chunkText, tokenize, encodeWav, validateInput } from '../extension/tts-core.mjs';

test('article chunking preserves text and bounds inference inputs', () => {
  const text = 'A short sentence. A second sentence with punctuation! '.repeat(100);
  const chunks = chunkText(text);
  assert.equal(chunks.join(' '), text.trim());
  assert.ok(chunks.every(chunk => chunk.length <= 350 && chunk.length > 0));
  assert.ok(chunkText('a'.repeat(1000)).every(chunk => chunk.length <= 350));
});

test('tokenizer matches the Python KittenTTS symbol table and separators', () => {
  // Reference generated by the installed KittenTTS TextCleaner, not this code.
  assert.deepEqual(Array.from(tokenize('həlˈoʊ wˈɜːld .'), Number),
    [0, 50, 83, 54, 156, 57, 135, 16, 65, 156, 87, 158, 54, 46, 16, 4, 10, 0]);
});

test('WAV output has real PCM framing, clamping, and speed-scaled pauses', () => {
  const wav = encodeWav([Float32Array.of(-2, 0, 2)], 1.5);
  const view = new DataView(wav);
  assert.equal(new TextDecoder().decode(wav.slice(0, 4)), 'RIFF');
  assert.equal(view.getUint32(24, true), 24000);
  assert.equal(view.getUint32(40, true), (3 + 1600) * 2);
  assert.equal(view.getInt16(44, true), -32767);
  assert.equal(view.getInt16(48, true), 32767);
});

test('invalid synthesis requests are rejected before inference', () => {
  const voices = { Luna: 'expr-voice-3-f' };
  for (const speed of [NaN, Infinity, 0, 3, '1.5', true]) {
    assert.throws(() => validateInput({ text: 'hello', voice: 'Luna', speed }, voices));
  }
  assert.throws(() => validateInput({ text: 'a'.repeat(60001), voice: 'Luna', speed: 1 }, voices));
  assert.throws(() => validateInput({ text: 'hello', voice: 'unknown', speed: 1 }, voices));
});
